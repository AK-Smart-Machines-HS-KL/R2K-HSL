def _merge_duplicate_waypoints(wps, eps=WP_MERGE_EPS_M):
    """Merge consecutive waypoints at (nearly) the same position into one
    entry with the summed hold_duration. The 7B copies its few-shot example,
    which encodes a pause as a DUPLICATE waypoint with hold_duration (live
    2026-09-05: 'left wing, pause 2s, right wing' compiled to
    FIRST(2,2.5), SECOND(2,2.5)[2s], THIRD(2,-2.5)). Labels renumbered so
    the executor's lookup table stays sequential."""
    merged = []
    for w in wps:
        if merged and abs(merged[-1]["x"] - w["x"]) <= eps \
                   and abs(merged[-1]["y"] - w["y"]) <= eps:
            merged[-1]["hold_duration"] += w.get("hold_duration", 0.0)
        else:
            merged.append(dict(w))
    labels = ["FIRST", "SECOND", "THIRD", "FOURTH", "FIFTH", "SIXTH",
              "SEVENTH", "EIGHTH"]
    for i, w in enumerate(merged):
        w["label"] = labels[i] if i < len(labels) else f"WP{i + 1}"
    return merged

