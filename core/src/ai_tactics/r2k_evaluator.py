def _parse_task_bot(clause):
    """Split an optional leading bot name or scope tokens from a task clause.
    Returns (bot_or_"ALL_BOTS", remaining_text, prefixed).
    prefixed=False means no explicit bot/scope: the caller decides defaults
    (task verbs -> blue1, bare control verbs -> fleet-wide)."""
    m = DEMO_BOT_PREFIX_RE.match(clause)
    if m:
        return _canon_bot(m.group(1)), m.group(2).strip(), True
    text = clause
    stripped = False
    while True:
        m = DEMO_SCOPE_TOKEN_RE.match(text)
        if not m:
            break
        text = text[m.end():]
        stripped = True
    if stripped:
        m = DEMO_SCOPE_BOTS_RE.match(text)
        if m:
            text = text[m.end():]
        return "ALL_BOTS", text.strip(), True
    return DEMO_DEFAULT_BOT, clause, False

