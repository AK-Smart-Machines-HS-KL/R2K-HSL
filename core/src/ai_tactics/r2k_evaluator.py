def _demo_target_for_bot(bot, bx, by):
    """Return the current target label and advance if the bot has arrived.
    On final-waypoint arrival the waypath ENDS: the bot is parked (Hold) so
    the executor stops re-issuing the last Move — otherwise any external
    displacement (drag) makes the PD walk the bot back to the old target."""
    st = _demo_bot_state(bot)
    wps = st["waypoints"]
    if not wps:
        return None
    wp = wps[st["target_idx"]]
    dist = math.hypot(bx - wp["x"], by - wp["y"])
    if dist < DEMO_ARRIVAL_DIST:
        hold = wp.get("hold_duration", 0)
        if hold > 0:
            if st["arrival_time"] == 0:
                st["arrival_time"] = time.time()
                return wp["label"]
            elif time.time() - st["arrival_time"] < hold:
                return wp["label"]
        # Advance to next WP, but don't loop past the last one
        if st["target_idx"] + 1 < len(wps):
            st["target_idx"] = st["target_idx"] + 1
            st["arrival_time"] = 0
            wp = wps[st["target_idx"]]
        elif dist < DEMO_PARK_DIST:
            # Waypath complete → park (waypath cleared; stopped_idx reset so
            # "resume" replays the waypath from the start)
            st["waypoints"] = []
            st["arrival_time"] = 0
            st["stopped_idx"] = 0
            st["fast_cmd"] = {"action": "Hold"}
            _write_hold_strategy(bot)
            print(f"🏁 [{bot}] waypath complete — parked", flush=True)
            return None
        # else: not yet close enough to park — keep closing in
    return wp["label"]

