def _handle_compound_task(clause, ents):
    """Split on comma-only (digit/chain guards). Sub-clauses containing
    instant verbs (control, look/say, face/turn) route independently.
    Move-chain sub-clauses (go/move/draw/approach/patrol) are reassembled
    with 'then' connectors so the 7B compiler sees the full sequence:
    'go to wing, pause 2s, go to wing' becomes one compile task, not two
    overwrites. Bot prefix parsed once and prepended to each sub-clause
    (otherwise 'blue_2 go to wing, pause' loses blue_2 on the second
    sub-clause → ALL_BOTS → blue_1 also moves, 2026-09-06)."""
    m = DEMO_BOT_PREFIX_RE.match(clause)
    if m:
        prefix = m.group(1)
        rest = m.group(2).strip()
    else:
        prefix = None
        rest = clause
    subs = _DEMO_COMMA_SEP_RE.split(rest)
    if len(subs) > 1:
        # Check if ALL sub-clauses are compiler vocabulary (move verbs)
        # If so, rejoin as a single chain so the 7B produces one waypath.
        move_verbs = ('go', 'goto', 'move', 'drive', 'draw', 'approach',
                       'patrol', 'trace', 'return', 'circle', 'pause', 'wait')
        all_compiler = all(
            any(s.strip().startswith(v) for v in move_verbs)
            for s in subs
        )
        if all_compiler:
            rejoined = " then ".join(s.strip() for s in subs)
            full = (prefix + " " + rejoined) if prefix else rejoined
            _handle_task_clause(full, ents)
        else:
            for c in subs:
                c = c.strip()
                if c:
                    full = (prefix + " " + c) if prefix else c
                    _handle_task_clause(full, ents)
    else:
        _handle_task_clause(clause, ents)  # no split needed — original


def _handle_task_clause(clause, ents):
    """Route one task clause to its bot(s): fast-path verbs, coordinate
    fast-path, or 7B compilation. Scope tokens (all/both/yahbooms/sim)
    address every blue bot in the world state.

    Control verbs (stop/resume/restart/go home) are FLEET-WIDE when
    unprefixed — an operator's bare "stop" must always halt the show
    (lab finding 2026-08-30: per-bot default left the vision bot moving).
    An EXPLICIT bot prefix wins (lab finding 2026-08-31: "blue_2 redo"
    replayed both bots' waypaths — the prefix must scope the verb).
    Task verbs stay per-bot (unprefixed = blue1, backward compatible)."""
    blue_bots = sorted(k for k in ents if k.startswith("blue"))
    if not blue_bots and not CALIB:
        return
    # Fleet-stop safety: control-flavored tasks must NEVER reach the compiler
    # (probe F5: "stop all bots" compiled a hallucinated goal-to-goal patrol)
    if re.match(r'^(?:stop|halt)\s+(?:all|every|bots|everyone)\b', clause):
        stop_targets = (["y1", "y2", "k1"] if CALIB else blue_bots)
        for bot in stop_targets:
            _demo_stop_bot(bot)
        return
    bot, text, prefixed = _parse_task_bot(clause)
    if CALIB:
        # Hardware identity list (relay keys). Bots absent from the relay
        # simply no-op in the bridge (no publisher, no assignment effect).
        hw_bots = ["y1", "y2", "k1"]
        if bot == "ALL_BOTS" or (text in DEMO_CONTROL_VERBS and not prefixed):
            targets = hw_bots
        elif not prefixed:
            targets = ["k1"]   # field-first default in calib
        else:
            targets = [_canon_bot(bot)]
    else:
        if bot == "ALL_BOTS" or (text in DEMO_CONTROL_VERBS and not prefixed):
            targets = blue_bots
        else:
            targets = [bot]
    if not text:
        return

    # --- CALIB: home = odom origin for hardware goto bots (2026-09-08).
    # "y1 go to home" / "y1 return" / bare "home" — the demo waypath
    # go-home is executor-driven (sim semantics, dead for hardware; live:
    # the command compiled with the 7B and drove nothing). For hardware
    # the calibration start pose IS the odom origin — instant Goto(0,0).
    if CALIB and any(b in DEMO_GOTO_BOTS for b in targets):
        if re.match(r'^(?:go\s*to\s*|goto\s*|drive\s+to\s*|go\s+)?'
                    r'(?:home|origin|start|return(?:\s+to\s+start)?)$', text):
            for b in targets:
                if b in DEMO_GOTO_BOTS:
                    _demo_goto_cmd(b, 0.0, 0.0)
            print("🏠 HOME = Goto(0,0) — calibration start pose (odom origin)",
                  flush=True)
            return

    # --- Fast-path control commands (bypass compiler, instant response) ---
    if text in DEMO_FAST_STOP:
        for b in targets:
            _demo_stop_bot(b)
        return
    if text in DEMO_FAST_RESUME:
        for b in targets:
            _demo_resume_bot(b)
        return
    if text in DEMO_FAST_RESTART:
        for b in targets:
            _demo_restart_bot(b)
        return
    if text in DEMO_FAST_HOME:
        for b in targets:
            _demo_go_home_bot(b)
        return

    # --- CALIB: Yahboom open-loop TimedMove (encoder odom unreliable — slip).
    # "y1 forward 0.5" / "y1 back 0.3" / "y1 turn 90" (+ = CCW). Sequential
    # for fleets: yahbooms drive one at a time (first target in list first).
    if CALIB:
        m = re.match(r'^(forward|back|backward)s?\s+(\d+(?:\.\d+)?)$', text)
        if m:
            dist = float(m.group(2))
            vx = Y_CALIB_VX * (1.0 if m.group(1).startswith('for') else -1.0)
            for b in targets:
                if b in ("y1", "y2"):
                    dur = dist / Y_CALIB_VX
                    _write_assignment(b, {"action": "TimedMove", "vx": vx,
                                          "vyaw": 0.0, "duration_s": round(dur, 3),
                                          "id": time.time()})
                    print(f"⏱ TIMED [{b}]: {m.group(1)} {dist}m @ {abs(vx)}m/s, "
                          f"{dur:.2f}s (open-loop)", flush=True)
                elif b == "k1":
                    print("⚠ k1 has closed-loop Goto — use 'k1 go to (x,y)'", flush=True)
            return
        m = re.match(r'^turn\s+(-?\d+(?:\.\d+)?)\s*(?:deg(?:rees)?|[o°])?$', text)
        if m:
            # CLOSED-LOOP turn (2026-09-08): routes to the relative-Face
            # machinery (estimator-yaw feedback, P-control, arrival latch,
            # spin caps) — NOT open-loop timing. Live evidence: the board's
            # actual yaw authority is ~0.27 rad/s vs the 0.5 commanded
            # (turn 45 -> +23.5°) and sub-0.5s commands are swallowed by
            # motor spin-up (turn 10/15 -> nothing). Odom YAW tracks the
            # physical body (gyro-fused) unlike wheel-distance — closing
            # the loop on it is legitimate and fixes both problems.
            # SIGN (user 2026-09-08, "counter intuitive"): positive =
            # CLOCKWISE/right — the boot-compass convention (nose north,
            # turn 90 -> nose east). ROS yaw is CCW-positive, hence the
            # negation.
            deg = float(m.group(1))
            for b in targets:
                _demo_face_cmd(b, relative=-math.radians(deg))
            print(f"🔁 TURN: {deg:+.0f}° closed-loop on odom yaw "
                  f"(+ = clockwise/right, arrival-latched; slow-authority "
                  f"bots just take longer)", flush=True)
            return

    # --- Calibration Goto (closed-loop odom, no digital twin) ---
    # "k1 go to (1,0)" and "y1 go to (0.5,0)" route to the odom-loop action
    # (bridge drives on the bot's OWN odometry); "blue1 go to (1,0)" goes to
    # the sim-pose Move. Mixed prefix routes each correctly. Yahboom = K1
    # field-test rehearsal (2026-09-08): same pipeline, coarse arrival.
    if any(b in DEMO_GOTO_BOTS for b in targets):
        m = DEMO_COORD_RE.match(text)
        if m:
            for b in targets:
                if b in DEMO_GOTO_BOTS:
                    _demo_goto_cmd(b, float(m.group(1)), float(m.group(2)))
                else:
                    _demo_direct_move([b], float(m.group(1)), float(m.group(2)))
            return

    # --- Coordinate fast-path (explicit coords, no LLM): seed a ONE-waypoint
    # waypath — the PROVEN machinery (evaluator arrival + park at 0.2m ->
    # Hold; drag_twin's waypath-watch sees the 3B's plain Move targets).
    # The round-5 Seq/latch experiment here caused the drag_twin teleport
    # loop — reverted 2026-09-05. ---
    m = DEMO_COORD_RE.match(text)
    if m:
        _demo_direct_move(targets, float(m.group(1)), float(m.group(2)))
        return

    # --- Sequence chains: "<step>, then <step>..." Decision table (5d):
    #   all instant steps (face/turn/rotate/look/say/pause) -> Seq (bridge)
    #   all move/pause steps (goto coords)                     -> WAYPATH
    #     (proven machinery; drag_twin sees the 3B's plain Move targets —
    #      chained Seq-moves caused the teleport loop, rewound 5c)
    #   instant + move mixed                                    -> rejected
    #   anything else (compile vocabulary)                      -> 7B below
    segments = DEMO_CHAIN_SPLIT_RE.split(text)
    if len(segments) > 1:
        steps = [_chain_step(s) for s in segments]
        move_segs = [_chain_move_segment(s) for s in segments]
        has_instant = any(s is not None and s.get('action') != 'Pause'
                          for s in steps)
        has_move = any(ms is not None and ms['kind'] == 'move'
                       for ms in move_segs)
        if all(s is not None for s in steps) and (has_instant or not has_move):
            if bot == "ALL_BOTS":
                # Explicit "all" scope overrides the one-bot-per-chain rule
                # (user 2026-09-06): every blue bot runs the same sequence.
                for b in targets:
                    _demo_seq_cmd(b, steps)
                return
            seq_bot = bot if prefixed else DEMO_FACE_DEFAULT_BOT
            if seq_bot in DEMO_HEAD_K1_ALIASES:
                seq_bot = DEMO_FACE_DEFAULT_BOT   # K1 has no target slot
            _demo_seq_cmd(seq_bot, steps)
            return
        if all(ms is not None for ms in move_segs) and has_move:
            wp_targets = [DEMO_FACE_DEFAULT_BOT if b in DEMO_HEAD_K1_ALIASES
                          else b for b in targets]
            for b in wp_targets:
                _demo_waypath_chain(b, move_segs, ents)
            return
        if has_instant and has_move:
            print(f"⚠ \"{clause}\" mixes facing and move steps.", flush=True)
            print("   Chains are either moves+pauses OR facing/head steps — "
                  'split them: e.g. "face west" first, then "go to (1,1)".',
                  flush=True)
            return
        # compile vocabulary present -> the 7B owns the compound (below)

    # --- Head fast-path (look/say): default blue_1 (body bot — bare 'say'
    # triggers the bridge body-gesture fork). Camera work = 'blue_2 ...'.
    # k1/k1_bot prefix reroutes inside _demo_head_cmd/_demo_gesture_cmd. ---
    if text in DEMO_HEAD_LOOK:
        pan, tilt = DEMO_HEAD_LOOK[text]
        head_targets = [DEMO_HEAD_DEFAULT_BOT] if not prefixed else targets
        for b in head_targets:
            _demo_head_cmd(b, pan, tilt)
        return
    if text in DEMO_HEAD_GESTURES:
        head_targets = [DEMO_HEAD_DEFAULT_BOT] if not prefixed else targets
        for b in head_targets:
            _demo_gesture_cmd(b, DEMO_HEAD_GESTURES[text])
        return

    # --- Face fast-path (body turn-in-place): default blue_1 ---
    # CALIB uses the boot compass (yaw 0 = north — the power-cycle ritual);
    # demo keeps the world frame (sim twins spawn facing east/+X).
    face_map = DEMO_FACE_ABS_CALIB if CALIB else DEMO_FACE_ABS
    face_targets = [DEMO_FACE_DEFAULT_BOT] if not prefixed else [
        DEMO_FACE_DEFAULT_BOT if b in DEMO_HEAD_K1_ALIASES else b for b in targets]
    if text in face_map:
        for b in face_targets:
            _demo_face_cmd(b, yaw=face_map[text])
        return
    if text in DEMO_TURN_REL:
        for b in face_targets:
            _demo_face_cmd(b, relative=DEMO_TURN_REL[text])
        return
    m = DEMO_ROTATE_RE.match(text)
    if m:
        for b in face_targets:
            _demo_face_cmd(b, relative=math.radians(float(m.group(1))))
        return

    # --- Facing/instant words must not reach the 7B: it has no facing
    # concept and would guess coordinates for them (the original
    # "face west, then go to 1,1" garbage compile). Landmark/shape
    # compounds WITHOUT these words compile normally. ---
    if DEMO_INSTANT_WORD_RE.search(text):
        print(f"⚠ \"{clause}\" mixes compile and facing/head commands.", flush=True)
        print("   Split them: run the compiler task (landmark/shape) and the "
              'facing/head command ("face west", "say no", ...) separately.',
              flush=True)
        return

    # --- Heading-relative guard: "forward/backward N m" has no yaw ground
    # truth (v7 Task 3a) — the compiler would guess garbage coordinates ---
    if DEMO_HEADING_REL_RE.search(text):
        print(f"⚠ \"{text}\" is heading-relative (forward/backward) — bots have no "
              f"yaw in the world model yet, so the compiler would guess. "
              f"Use coordinates instead: e.g. \"go to (2, 0)\" or a landmark.", flush=True)
        return

    # --- Verb guard: scope-only clauses must not reach the compiler ---
    if not DEMO_TASK_VERB_RE.search(text):
        print(f"⚠ no actionable verb in \"{clause}\" — ignored", flush=True)
        return

    # --- CALIB vocabulary freeze (cleanup 2026-09-08): everything that
    # falls through to here is compiler vocabulary (landmarks/shapes/
    # patrols/ball/via-points) — demo-mode features that drive sim bots.
    # In calib they compiled dead waypaths ("y1 go to home" once compiled
    # with the 7B and drove nothing). Reject loudly with the accepted list.
    if CALIB:
        print(f"⚠ \"{clause}\" is demo-mode (compiler) vocabulary — calib is "
              f"a hardware-only field stack.", flush=True)
        print("   Calib accepts: yN/k1 go to (x,y) | go to home | return | "
              "face <dir> | say yes/no | look <dir> | stop |", flush=True)
        print("   yN forward/back <m> | yN turn <deg> | exec <runbook> | "
              "results. Chains/landmarks/shapes = demo mode.", flush=True)
        return

    # --- Normal path: compile task via 7B LLM (per bot) ---
    for b in targets:
        _compile_demo_task(b, text, ents)

