def _chain_step(text):
    """One fast-path step -> Seq step dict, or None if not chain-able.
    POSITION-MOVING steps (coordinate moves) are deliberately NOT chain-able:
    drag_twin only recognizes plain waypath Move targets (drag_twin.py
    _refresh_targets) — chained moves made its idle-watch false-positive on
    commanded drives (stop + teleport-back + goto loop, 2026-09-05 rewind).
    Chains are non-motion steps only; run go-to as its own command."""
    text = text.strip()
    m = DEMO_PAUSE_STEP_RE.match(text)
    if m:
        return {"action": "Pause", "duration": float(m.group(1))}
    if text in DEMO_FACE_ABS:
        return {"action": "Face", "yaw": DEMO_FACE_ABS[text]}
    if text in DEMO_TURN_REL:
        return {"action": "Face", "relative_angle": DEMO_TURN_REL[text]}
    if text in DEMO_HEAD_LOOK:
        pan, tilt = DEMO_HEAD_LOOK[text]
        return {"action": "Head", "pan_deg": pan, "tilt_deg": tilt}
    if text in DEMO_HEAD_GESTURES:
        return {"action": "Head", "gesture": DEMO_HEAD_GESTURES[text],
                "cycles": hc.GESTURE_CYCLES}
    m = DEMO_ROTATE_RE.match(text)
    if m:
        return {"action": "Face", "relative_angle": math.radians(float(m.group(1)))}
    return None


