def _calib_damp_hint_tick():
    """Check if K1 hasn't moved within K1_DAMP_HINT_SECS after Goto.
    Fires ONCE per session — warns about DAMP mode, not absence or crash."""
    global _k1_damp_hint_armed, _k1_damp_hint_fired
    if not _k1_damp_hint_armed or _k1_damp_hint_fired:
        return
    if time.time() - _k1_goto_t0 < K1_DAMP_HINT_SECS:
        return
    _k1_damp_hint_armed = False
    try:
        with open(WAYPOINTS_PATH.replace('waypoints.json', 'k1_odom.json')) as f:
            o = json.load(f)
        dx = o.get('x', 0.0) - (_k1_goto_start[0] if _k1_goto_start else 0.0)
        dy = o.get('y', 0.0) - (_k1_goto_start[1] if _k1_goto_start else 0.0)
        dist_moved = math.hypot(dx, dy)
        if dist_moved < K1_DAMP_HINT_MIN_MOVE_M:
            print(f"⚠ K1 DAMP HINT: Goto sent but k1 didn't move in "
                  f"{K1_DAMP_HINT_SECS}s — DAMP mode active? (odom fresh, "
                  f"position unchanged)", flush=True)
            _k1_damp_hint_fired = True
        else:
            _k1_damp_hint_armed = False  # moved fine — no hint needed
    except Exception:
        pass

